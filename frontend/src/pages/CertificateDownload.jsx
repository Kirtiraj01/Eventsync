import { useEffect, useState } from "react";
import { useParams } from "react-router-dom";
import { motion } from "framer-motion";
import Nav from "../components/Nav";
import Footer from "../components/Footer";
import PageTransition from "../components/PageTransition";
import { downloadCertificateUrl } from "../api/clubhub";
import { IconDownload, IconShare, IconClock, IconAward } from "../icons/Icons";

export default function CertificateDownload() {
  const { registrationId } = useParams();
  const [status, setStatus] = useState("checking"); // checking | ready | not_ready | error
  const [errorMessage, setErrorMessage] = useState(null);

  const pdfUrl = downloadCertificateUrl(registrationId);

  useEffect(() => {
    let cancelled = false;
    setStatus("checking");

    fetch(pdfUrl, { method: "GET" })
      .then(async (res) => {
        if (cancelled) return;
        if (res.ok) {
          setStatus("ready");
        } else {
          const data = await res.json().catch(() => ({}));
          setErrorMessage(data.error || "Certificate not available yet");
          setStatus("not_ready");
        }
      })
      .catch((err) => {
        if (!cancelled) {
          setErrorMessage(err.message || "Couldn't reach the server");
          setStatus("error");
        }
      });

    return () => {
      cancelled = true;
    };
  }, [pdfUrl]);

  return (
    <div className="min-h-screen bg-night font-body flex flex-col text-[#F3F2F8]">
      <Nav />

      <PageTransition className="flex-1">
        <section className="max-w-3xl mx-auto px-6 py-14 sm:py-16 text-center">
          {status === "checking" && (
            <div className="py-24 flex flex-col items-center justify-center gap-3">
              <span className="w-5 h-5 rounded-full border-2 border-brand-lavender border-t-transparent animate-spin" />
              <p className="text-sm font-medium text-[#9E97B8]">Checking certificate status…</p>
            </div>
          )}

          {(status === "not_ready" || status === "error") && (
            <motion.div
              initial={{ scale: 0.95, opacity: 0 }}
              animate={{ scale: 1, opacity: 1 }}
              className="card rounded-3xl p-10 max-w-md mx-auto bg-surface-card border border-surface-border shadow-glow-sm"
            >
              <span className="w-14 h-14 rounded-full bg-amber-950/50 text-amber-400 border border-amber-800/60 flex items-center justify-center mx-auto mb-5 shadow-xs">
                <IconClock width={26} height={26} />
              </span>
              <h1 className="font-heading font-extrabold text-2xl text-[#F3F2F8] mb-2 tracking-tight">Not ready yet</h1>
              <p className="text-sm text-[#9E97B8] leading-relaxed font-medium">
                {status === "error"
                  ? `Couldn't reach EventSync's server. ${errorMessage || ""}`
                  : errorMessage || "Your certificate unlocks once generated by the club organizer after door check-in."}
              </p>
            </motion.div>
          )}

          {status === "ready" && (
            <>
              <motion.div
                initial={{ scale: 0 }}
                animate={{ scale: 1 }}
                transition={{ type: "spring", stiffness: 350, damping: 20 }}
                className="w-16 h-16 rounded-full bg-brand-lavender/10 border border-brand-lavender/25 text-brand-lavender flex items-center justify-center mx-auto mb-5 shadow-glow-sm"
              >
                <IconAward width={32} height={32} />
              </motion.div>

              <h1 className="font-heading font-extrabold text-3xl sm:text-4xl text-[#F3F2F8] mb-2 tracking-tight">
                Your certificate is ready 🎉
              </h1>
              <p className="text-[#9E97B8] text-sm mb-8 font-medium">
                Registration ID <code className="text-brand-lavender font-bold bg-surface-elevated px-2.5 py-1 rounded-full border border-surface-border">{registrationId}</code>
              </p>

              <motion.div
                initial={{ opacity: 0, y: 15 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ duration: 0.4 }}
                className="border-2 border-surface-border rounded-3xl overflow-hidden bg-surface-card shadow-glow-sm"
              >
                <object data={pdfUrl} type="application/pdf" className="w-full h-[520px]">
                  <div className="p-12 text-sm text-[#9E97B8] font-medium flex flex-col items-center gap-3">
                    <p>Your browser doesn't preview PDFs inline.</p>
                    <a
                      href={pdfUrl}
                      target="_blank"
                      rel="noreferrer"
                      className="btn-primary text-xs font-semibold px-5 py-2.5 rounded-full inline-block shadow-glow-sm cursor-pointer"
                    >
                      Open certificate directly
                    </a>
                  </div>
                </object>
              </motion.div>

              <div className="flex flex-col sm:flex-row items-center justify-center gap-3.5 mt-8">
                <motion.a
                  whileHover={{ scale: 1.02, y: -2 }}
                  whileTap={{ scale: 0.98 }}
                  href={pdfUrl}
                  target="_blank"
                  rel="noreferrer"
                  download
                  className="btn-primary font-semibold rounded-full px-8 py-3.5 flex items-center gap-2 text-sm w-full sm:w-auto justify-center shadow-glow-sm cursor-pointer"
                >
                  <IconDownload width={16} height={16} /> Download PDF
                </motion.a>
                <motion.button
                  whileHover={{ scale: 1.02, y: -2 }}
                  whileTap={{ scale: 0.98 }}
                  onClick={() => window.open(pdfUrl, "_blank")}
                  className="btn-secondary font-semibold rounded-full px-8 py-3.5 flex items-center gap-2 text-sm w-full sm:w-auto justify-center cursor-pointer"
                >
                  <IconShare width={16} height={16} /> View Certificate
                </motion.button>
              </div>

              <p className="text-xs text-[#9E97B8] font-medium mt-6 max-w-lg mx-auto leading-relaxed">
                The certificate PDF includes a cryptographically verifiable QR code — anyone can scan it to check authenticity without logging in.
              </p>
            </>
          )}
        </section>
      </PageTransition>

      <Footer />
    </div>
  );
}
